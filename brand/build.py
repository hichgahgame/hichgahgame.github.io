#!/usr/bin/env python3
"""Builds the Hichgah brand outputs from brand/tokens.json.

    python3 brand/build.py

Writes brand/tokens.css (the website) and brand/unity/Assets/Hichgah/Brand/ (games; copy them in with
brand/sync-unity.sh). Fails if a text colour pair drops below WCAG AA contrast.
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
TOKENS = json.loads((HERE / "tokens.json").read_text())
UNITY_DIR = HERE / "unity" / "Assets" / "Hichgah" / "Brand"
HEADER = "Generated by brand/build.py from brand/tokens.json (hichgahgame.github.io). Do not edit by hand."


def resolve(ref):
    """'violet.deep' -> palette hex, 'ink' -> neutral hex, '#abc123' -> itself."""
    if ref.startswith("#"):
        return ref.upper()
    if "." in ref:
        hue, shade = ref.split(".")
        return TOKENS["palette"][hue][shade]
    return TOKENS["neutral"][ref]


def luminance(hex_):
    def channel(c):
        c /= 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (int(hex_[i:i + 2], 16) for i in (1, 3, 5))
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def contrast(a, b):
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def pascal(name):
    return "".join(part.capitalize() for part in name.split("-"))


def check_contrast():
    """Every pair here carries readable text, so each needs at least 4.5:1."""
    pairs = []
    for mode, theme in TOKENS["theme"].items():
        t = {k: resolve(v) for k, v in theme.items()}
        for fg in ("text", "text-soft", "muted", "accent"):
            for bg in ("bg", "surface"):
                pairs.append((f"{mode}: {fg} on {bg}", t[fg], t[bg]))
    light = {k: resolve(v) for k, v in TOKENS["theme"]["light"].items()}
    pairs.append(("white on light accent (buttons)", "#FFFFFF", light["accent"]))
    for stop in TOKENS["gradient"]["dusk"]:
        pairs.append((f"white on dusk {stop}", "#FFFFFF", stop))
    for hue, shades in TOKENS["palette"].items():
        pairs.append((f"{hue}.deep on white", shades["deep"], "#FFFFFF"))
        pairs.append((f"ink on {hue}.soft", TOKENS["neutral"]["ink"], shades["soft"]))
    failed = False
    for label, fg, bg in pairs:
        ratio = contrast(fg, bg)
        if ratio < 4.5:
            failed = True
            print(f"  FAIL {ratio:4.1f}:1  {label}")
    if failed:
        sys.exit("Contrast check failed: fix tokens.json.")
    print(f"Contrast: all {len(pairs)} text pairs pass AA (4.5:1).")


def build_css():
    out = [f"/* {HEADER} */", ":root {"]
    for hue, shades in TOKENS["palette"].items():
        for shade, value in shades.items():
            suffix = "" if shade == "base" else f"-{shade}"
            out.append(f"  --hg-{hue}{suffix}: {value};")
    for name, value in TOKENS["neutral"].items():
        out.append(f"  --hg-{name}: {value};")
    for name, stops in TOKENS["gradient"].items():
        if not name.startswith("$"):
            out.append(f"  --hg-gradient-{name}: linear-gradient(135deg, {', '.join(stops)});")
    for name, ref in TOKENS["game"].items():
        if not name.startswith("$"):
            out.append(f"  --hg-{name}: {resolve(ref)};")
    fonts = TOKENS["font"]
    out.append(f'  --hg-font-display: "{fonts["display"]}", system-ui, sans-serif;')
    out.append(f'  --hg-font-serif: "{fonts["serif"]}", Georgia, "Times New Roman", serif;')
    out.append('  --hg-font-body: system-ui, -apple-system, "Segoe UI", Roboto, sans-serif;')
    for name, px in TOKENS["radius"].items():
        out.append(f"  --hg-radius-{name}: {px}px;")
    for name, px in TOKENS["space"].items():
        out.append(f"  --hg-space-{name}: {px}px;")
    for name, s in TOKENS["motion"].items():
        if not name.startswith("$"):
            out.append(f"  --hg-motion-{name}: {s}s;")
    out.append("")
    out.append("  /* Page roles (light). Game pages override these in their own theme.css. */")
    out += theme_vars("light")
    out.append("}")
    dark = "\n".join(theme_vars("dark", indent="    "))
    out.append("")
    out.append("@media (prefers-color-scheme: dark) {")
    out.append('  :root:not([data-theme="light"]) {')
    out.append(dark)
    out.append("  }")
    out.append("}")
    out.append("")
    out.append(':root[data-theme="dark"] {')
    out += theme_vars("dark")
    out.append("}")
    (HERE / "tokens.css").write_text("\n".join(out) + "\n")


def theme_vars(mode, indent="  "):
    return [f"{indent}--{role}: {resolve(ref)};" for role, ref in TOKENS["theme"][mode].items()]


def hex_literal(value):
    return f"Hex(0x{value[1:]})"


def build_unity():
    UNITY_DIR.mkdir(parents=True, exist_ok=True)
    cs = [
        f"// {HEADER}",
        "// Copy into a game with brand/sync-unity.sh; change colours in tokens.json, not here.",
        "using UnityEngine;",
        "",
        "namespace Hichgah.Brand",
        "{",
        "    /// <summary>The Hichgah palette. Each hue has Base (fills), Deep (edges, shadows, text on light),",
        "    /// Soft (light panels) and Night (accents on dark backgrounds).</summary>",
        "    public static class HichgahColors",
        "    {",
    ]
    for hue, shades in TOKENS["palette"].items():
        cs.append(f"        public static class {pascal(hue)}")
        cs.append("        {")
        for shade, value in shades.items():
            cs.append(f"            public static readonly Color {pascal(shade)} = {hex_literal(value)};")
        cs.append("        }")
        cs.append("")
    for name, value in TOKENS["neutral"].items():
        cs.append(f"        public static readonly Color {pascal(name)} = {hex_literal(value)};")
    cs.append("")
    cs.append("        /// <summary>Meanings every game shares, so a star or a reward looks the same everywhere.</summary>")
    cs.append("        public static class Game")
    cs.append("        {")
    for name, ref in TOKENS["game"].items():
        if not name.startswith("$"):
            cs.append(f"            public static readonly Color {pascal(name)} = {hex_literal(resolve(ref))};")
    cs.append("        }")
    cs.append("")
    cs.append("        internal static Color Hex(uint rgb) =>")
    cs.append("            new Color32((byte)(rgb >> 16), (byte)(rgb >> 8), (byte)rgb, 255);")
    cs.append("    }")
    cs.append("")
    cs.append("    /// <summary>Brand gradients, left to right. Now is the signature: logo ring, splash, celebrations.</summary>")
    cs.append("    public static class HichgahGradients")
    cs.append("    {")
    for name, stops in TOKENS["gradient"].items():
        if name.startswith("$"):
            continue
        cs.append(f"        public static readonly Color[] {pascal(name)}Stops = {{ {', '.join('HichgahColors.' + hex_literal(s) for s in stops)} }};")
        cs.append(f"        public static Gradient {pascal(name)} => Build({pascal(name)}Stops);")
    cs += [
        "",
        "        static Gradient Build(Color[] stops)",
        "        {",
        "            var colors = new GradientColorKey[stops.Length];",
        "            for (int i = 0; i < stops.Length; i++)",
        "                colors[i] = new GradientColorKey(stops[i], stops.Length == 1 ? 0f : i / (stops.Length - 1f));",
        "            var gradient = new Gradient();",
        "            gradient.SetKeys(colors, new[] { new GradientAlphaKey(1f, 0f), new GradientAlphaKey(1f, 1f) });",
        "            return gradient;",
        "        }",
        "    }",
        "",
        "    /// <summary>Font family names. Display is for titles and buttons; Serif for calm, reflective lines.</summary>",
        "    public static class HichgahFonts",
        "    {",
    ]
    for name, family in TOKENS["font"].items():
        cs.append(f'        public const string {pascal(name)} = "{family}";')
    cs += [
        "    }",
        "",
        "    /// <summary>Corner radii and spacing, in reference pixels.</summary>",
        "    public static class HichgahLayout",
        "    {",
    ]
    for name, px in TOKENS["radius"].items():
        cs.append(f"        public const float Radius{pascal(name)} = {px}f;")
    for name, px in TOKENS["space"].items():
        cs.append(f"        public const float Space{pascal(name)} = {px}f;")
    cs += [
        "    }",
        "",
        "    /// <summary>Animation durations in seconds. Calm is the brand: prefer Base and Calm, Fast only for taps.</summary>",
        "    public static class HichgahMotion",
        "    {",
    ]
    for name, s in TOKENS["motion"].items():
        if not name.startswith("$"):
            cs.append(f"        public const float {pascal(name)} = {s}f;")
    cs += ["    }", "}"]
    (UNITY_DIR / "HichgahBrand.cs").write_text("\n".join(cs) + "\n")
    (UNITY_DIR / "Hichgah.Brand.asmdef").write_text(json.dumps(
        {"name": "Hichgah.Brand", "rootNamespace": "Hichgah.Brand", "autoReferenced": True}, indent=4) + "\n")


if __name__ == "__main__":
    check_contrast()
    build_css()
    build_unity()
    print("Wrote brand/tokens.css and brand/unity/Assets/Hichgah/Brand/.")
